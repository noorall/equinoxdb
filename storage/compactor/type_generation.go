package compactor

import "equinox/storage/store"

// sstGeneration represents the SST files within a generation.
// 000001-01.sst, 000001-02.sst would be in the same generation
// 000001 each with different sequence numbers.
type sstGeneration struct {
	id            int
	files         []store.FileStat
	parseFileName store.ParseFileNameFunc
}

func newSstGeneration(id int, parseFileNameFunc store.ParseFileNameFunc) *sstGeneration {
	return &sstGeneration{
		id:            id,
		parseFileName: parseFileNameFunc,
	}
}

// size returns the total size of the files in the generation.
func (t *sstGeneration) size() uint64 {
	var n uint64
	for _, f := range t.files {
		n += uint64(f.Size)
	}
	return n
}

// compactionLevel returns the level of the files in this generation.
func (t *sstGeneration) level() int {
	// Level 0 is always created from the result of a cache compaction.  It generates
	// 1 File with a sequence num of 1.  Level 2 is generated by compacting multiple
	// level 1 files.  Level 3 is generate by compacting multiple level 2 files.  Level
	// 4 is for anything else.
	_, seq, _ := t.parseFileName(t.files[0].Path)
	if seq < 4 {
		return seq
	}

	return 4
}

// count returns the number of files in the generation.
func (t *sstGeneration) count() int {
	return len(t.files)
}

// hasTombstones returns true if there are keys removed for any of the files.
func (t *sstGeneration) hasTombstones() bool {
	for _, f := range t.files {
		if f.HasTombstone {
			return true
		}
	}
	return false
}

type SstGenerations []*sstGeneration

func (a SstGenerations) Len() int           { return len(a) }
func (a SstGenerations) Less(i, j int) bool { return a[i].id < a[j].id }
func (a SstGenerations) Swap(i, j int)      { a[i], a[j] = a[j], a[i] }
func (a SstGenerations) hasTombstones() bool {
	for _, g := range a {
		if g.hasTombstones() {
			return true
		}
	}
	return false
}

func (a SstGenerations) level() int {
	var level int
	for _, g := range a {
		lev := g.level()
		if lev > level {
			level = lev
		}
	}
	return level
}

func (a SstGenerations) chunk(size int) []SstGenerations {
	var chunks []SstGenerations
	for len(a) > 0 {
		if len(a) >= size {
			chunks = append(chunks, a[:size])
			a = a[size:]
		} else {
			chunks = append(chunks, a)
			a = a[len(a):]
		}
	}
	return chunks
}

func (a SstGenerations) IsSorted() bool {
	if len(a) == 1 {
		return true
	}

	for i := 1; i < len(a); i++ {
		if a.Less(i, i-1) {
			return false
		}
	}
	return true
}
